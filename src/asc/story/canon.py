"""Story canon: the declared state of a work, kept outside the model context.

The canon is the ground truth a continuity audit compares against. It is
deliberately small and human-editable: characters, facts, locations, chapters
and foreshadowing. Everything the audit knows about the world comes from here
or from explicit markers in the text (see :mod:`asc.story.text`), never from a
language model's memory.

YAML is used when PyYAML is installed (it is a declared dependency); JSON is
always accepted so that the canon can be generated by other tooling.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

CANON_FILES = {
    "characters": ("characters",),
    "facts": ("facts",),
    "locations": ("locations",),
    "timeline": ("timeline", "chapters"),
    "foreshadowing": ("foreshadowing", "foreshadows"),
    "suppressions": ("suppressions", "intentional_contradictions"),
}

CHARACTER_STATUSES = {"alive", "dead", "missing", "unknown"}


class CanonError(ValueError):
    """Raised when the canon is missing a required field or is inconsistent."""


def _load_file(path: Path) -> dict[str, Any]:
    text = path.read_text(encoding="utf-8")
    if path.suffix.lower() == ".json":
        data = json.loads(text)
    else:
        try:
            import yaml
        except ModuleNotFoundError as exc:  # pragma: no cover - dependency is declared
            raise CanonError(
                f"{path.name}: loading YAML requires PyYAML (pip install -r requirements.txt)"
            ) from exc
        data = yaml.safe_load(text)
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise CanonError(f"{path.name}: the top level must be a mapping")
    return data


def _channel(data: dict[str, Any], keys: tuple[str, ...], path: Path) -> list[dict]:
    for key in keys:
        if key in data:
            value = data[key]
            if value is None:
                return []
            if not isinstance(value, list):
                raise CanonError(f"{path.name}: '{key}' must be a list")
            for item in value:
                if not isinstance(item, dict):
                    raise CanonError(f"{path.name}: entries of '{key}' must be mappings")
            return value
    return []


def chapter_key(value: Any) -> str | None:
    """Normalise a chapter reference (``ch2``, ``2``, ``第2章``) to ``ch02``."""
    if value is None:
        return None
    if isinstance(value, int):
        return f"ch{value:02d}"
    text = str(value).strip()
    match = re.search(r"(\d+)", text)
    if match:
        return f"ch{int(match.group(1)):02d}"
    return text or None


@dataclass(frozen=True)
class Character:
    id: str
    name: str
    aliases: tuple[str, ...] = ()
    status: str = "alive"
    status_since: str | None = None
    location: str | None = None
    age_at_start: int | None = None
    birthday_day: int | None = None  # day-of-year the character turns a year older
    knows: tuple[str, ...] = ()
    notes: str | None = None

    @property
    def all_names(self) -> tuple[str, ...]:
        return (self.name, *self.aliases)


@dataclass(frozen=True)
class Fact:
    id: str
    summary: str = ""
    terms: tuple[str, ...] = ()
    setup: str | None = None


@dataclass(frozen=True)
class Location:
    id: str
    travel_days: dict[str, float] = field(default_factory=dict)

    def days_from(self, other: str) -> float | None:
        """Days needed to travel from ``other`` to this location."""
        if other == self.id:
            return 0.0
        if other in self.travel_days:
            return float(self.travel_days[other])
        return None


@dataclass(frozen=True)
class Chapter:
    id: str
    day: float | None = None
    year: int | None = None
    location: str | None = None
    path: Path | None = None


@dataclass(frozen=True)
class Foreshadow:
    id: str
    description: str = ""
    setup: str | None = None
    payoff: str | None = None


@dataclass(frozen=True)
class Suppression:
    check: str
    subject: str = "*"
    scope: tuple[str, ...] = ()  # empty = every chapter
    reason: str = ""

    def covers(self, check: str, subject: str | None, chapter: str | None) -> bool:
        if self.check not in (check, "*"):
            return False
        if self.subject not in ("*", subject):
            return False
        return not self.scope or (chapter is not None and chapter in self.scope)


@dataclass
class Canon:
    root: Path
    characters: dict[str, Character] = field(default_factory=dict)
    facts: dict[str, Fact] = field(default_factory=dict)
    locations: dict[str, Location] = field(default_factory=dict)
    chapters: dict[str, Chapter] = field(default_factory=dict)
    foreshadowing: dict[str, Foreshadow] = field(default_factory=dict)
    suppressions: list[Suppression] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    # -- lookups ---------------------------------------------------------
    def character(self, key: str | None) -> Character | None:
        if not key:
            return None
        if key in self.characters:
            return self.characters[key]
        for char in self.characters.values():
            if key in char.all_names:
                return char
        return None

    def resolve_name(self, text: str) -> list[str]:
        """Character ids mentioned in a piece of text (longest alias first)."""
        found: list[str] = []
        for char in self.characters.values():
            for name in sorted(char.all_names, key=len, reverse=True):
                if len(name) >= 2 and name in text:
                    found.append(char.id)
                    break
        return found

    def chapter_order(self) -> list[str]:
        return sorted(self.chapters, key=lambda c: (self.chapters[c].day is None,
                                                   self.chapters[c].day or 0, c))

    def travel_days(self, origin: str | None, destination: str | None) -> float | None:
        if not origin or not destination:
            return None
        if origin == destination:
            return 0.0
        direct = self.locations.get(destination)
        if direct and (days := direct.days_from(origin)) is not None:
            return days
        reverse = self.locations.get(origin)
        if reverse and (days := reverse.days_from(destination)) is not None:
            return days
        return None


def load_canon(root: str | Path) -> Canon:
    """Load a canon directory.

    Recognised files (all optional, YAML or JSON):
    ``characters``, ``facts``, ``locations``, ``timeline``, ``foreshadowing``,
    ``suppressions``. Any of these may also be a list inside a single
    ``canon.{yaml,json}`` file.
    """
    root = Path(root)
    if not root.exists():
        raise CanonError(f"canon directory not found: {root}")

    canon = Canon(root=root)
    single = None
    for name in ("canon.yaml", "canon.yml", "canon.json"):
        if (root / name).is_file():
            single = _load_file(root / name)
            break

    def channel(kind: str) -> list[dict]:
        if single is not None:
            rows = _channel(single, CANON_FILES[kind], root / "canon")
            if rows:
                return rows
        rows: list[dict] = []
        for stem in CANON_FILES[kind]:
            for suffix in (".yaml", ".yml", ".json"):
                path = root / f"{stem}{suffix}"
                if path.is_file():
                    rows.extend(_channel(_load_file(path), CANON_FILES[kind] + (stem,), path))
        return rows

    for row in channel("characters"):
        cid = row.get("id")
        if not cid:
            raise CanonError("characters: every entry needs an 'id'")
        status = str(row.get("status") or "alive")
        if status not in CHARACTER_STATUSES:
            raise CanonError(f"character {cid}: unknown status '{status}'")
        canon.characters[cid] = Character(
            id=cid,
            name=str(row.get("name") or cid),
            aliases=tuple(row.get("aliases") or ()),
            status=status,
            status_since=chapter_key(row.get("status_since")),
            location=row.get("location"),
            age_at_start=row.get("age_at_start"),
            birthday_day=row.get("birthday_day"),
            knows=tuple(row.get("knows") or ()),
            notes=row.get("notes"),
        )

    for row in channel("facts"):
        fid = row.get("id")
        if not fid:
            raise CanonError("facts: every entry needs an 'id'")
        canon.facts[fid] = Fact(
            id=fid,
            summary=str(row.get("summary") or ""),
            terms=tuple(row.get("terms") or ()),
            setup=chapter_key(row.get("setup")),
        )

    for row in channel("locations"):
        lid = row.get("id")
        if not lid:
            raise CanonError("locations: every entry needs an 'id'")
        canon.locations[lid] = Location(
            id=lid,
            travel_days={k: v for k, v in (row.get("travel_days") or {}).items()},
        )

    for row in channel("timeline"):
        cid = chapter_key(row.get("id") or row.get("chapter"))
        if not cid:
            raise CanonError("timeline: every entry needs an 'id' (chapter)")
        canon.chapters[cid] = Chapter(
            id=cid,
            day=row.get("day"),
            year=row.get("year"),
            location=row.get("location"),
        )

    for row in channel("foreshadowing"):
        fid = row.get("id")
        if not fid:
            raise CanonError("foreshadowing: every entry needs an 'id'")
        canon.foreshadowing[fid] = Foreshadow(
            id=fid,
            description=str(row.get("description") or ""),
            setup=chapter_key(row.get("setup")),
            payoff=chapter_key(row.get("payoff")),
        )

    for row in channel("suppressions"):
        check = row.get("check")
        if not check:
            raise CanonError("suppressions: every entry needs a 'check'")
        canon.suppressions.append(Suppression(
            check=check,
            subject=row.get("subject") or "*",
            scope=tuple(chapter_key(c) for c in (row.get("scope") or ()) if chapter_key(c)),
            reason=str(row.get("reason") or ""),
        ))

    _validate(canon)
    return canon


def _validate(canon: Canon) -> None:
    for char in canon.characters.values():
        for fact_id in char.knows:
            if fact_id not in canon.facts:
                canon.warnings.append(f"character {char.id}: unknown fact '{fact_id}'")
    for fs in canon.foreshadowing.values():
        for chapter in (fs.setup, fs.payoff):
            if chapter and canon.chapters and chapter not in canon.chapters:
                canon.warnings.append(f"foreshadowing {fs.id}: unknown chapter '{chapter}'")
    for chapter in canon.chapters.values():
        if chapter.location and canon.locations and chapter.location not in canon.locations:
            canon.warnings.append(f"chapter {chapter.id}: unknown location '{chapter.location}'")


def load_chapters(text_dir: str | Path) -> list[Chapter]:
    """Load ``*.md`` / ``*.txt`` chapters, ordered by their leading number."""
    text_dir = Path(text_dir)
    if not text_dir.exists():
        raise CanonError(f"text directory not found: {text_dir}")
    paths = sorted(p for p in text_dir.iterdir()
                   if p.is_file() and p.suffix.lower() in {".md", ".txt", ".markdown"})
    chapters: list[Chapter] = []
    for path in paths:
        match = re.match(r"(?:ch|chapter|ep)?[_-]?(\d+)", path.stem, re.IGNORECASE)
        cid = f"ch{int(match.group(1)):02d}" if match else path.stem
        chapters.append(Chapter(id=cid, path=path))
    return sorted(chapters, key=lambda c: c.id)
