#!/usr/bin/env python3
"""Compare the L1 profile of two generated arms on the same task.

The two-stage slice and the direct draft differ in *what the model is given*,
not in what L1 measures: characters, required and avoided vocabulary,
forbidden-pattern density, the continuity audit (violations, severity, CED)
and the descriptive style statistics. This script runs exactly those existing
functions over two text arms and writes the numbers side by side.

    python3 scripts/compare_l1_arms.py --task t01 \
        --canon experiments/2026-10-full-t01/inputs/canon \
        --arm two-stage=experiments/2026-10-full-t01/relay-r2/responses \
        --arm s1-draft=runs/s1/text \
        --out experiments/2026-10-l1-pair-t01/comparison.json

An arm is either a directory of chapter files (``ch01.md`` …) or a directory
of recorded relay responses (``*.json`` with a ``text`` field). The second
form exists because a recorded run can outlive the prompt that produced it:
when a prompt changes, the replay contract refuses to re-serve the old answer
(``response_sha256``/``prompt_hash``), but the bytes that were generated are
still on record. Naming the chapter is done from the response key
(``...-stage_b-ch03-a1``) and falls back to sorted order.

**This is L1 only.** It says nothing about quality, interest or reader
preference (L2/L3 stay frozen), and an arm-level difference of a few percent
in descriptive statistics is not an effect: both arms are N=1, generated by
the same operator, and neither is a reproducible model (G5 unmet).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from asc.evaluation.harness import load_patterns  # noqa: E402
from asc.evaluation.scope import load_evaluation_scope  # noqa: E402
from asc.evaluation.metrics import (Document, find_forbidden, measure,  # noqa: E402
                                    density)
from asc.pipeline.tasks import load_tasks  # noqa: E402
from asc.story.continuity import audit_texts  # noqa: E402

DEFAULT_TASKS = REPO_ROOT / "benchmarks" / "protocol-v1" / "tasks.yaml"
DEFAULT_PATTERNS = REPO_ROOT / "harness" / "patterns.yaml"
MARKER_RE = re.compile(r"\{\{[^{}]*\}\}")
CHAPTER_RE = re.compile(r"(ch\d+)")
ATTEMPT_RE = re.compile(r"-a(\d+)$")


def _chapter_id(name: str, fallback: str) -> str:
    match = CHAPTER_RE.search(name)
    return match.group(1) if match else fallback


def load_arm(path: Path, scratch: Path) -> tuple[list[Document], str]:
    """Chapter markdown files, or recorded relay responses.

    Relay responses are staged as chapter files in ``scratch`` so that the
    continuity audit (which reads a directory) sees them exactly as it would
    see a run output.
    """
    if not path.is_dir():
        raise SystemExit(f"arm directory not found: {path}")
    markdown = sorted(p for p in path.iterdir()
                      if p.is_file() and p.suffix.lower() in {".md", ".txt"})
    if markdown:
        return [Document(path=p, text=p.read_text(encoding="utf-8"))
                for p in markdown], "chapter_files"
    responses = sorted(p for p in path.iterdir()
                       if p.is_file() and p.suffix.lower() == ".json")
    # A relay directory holds every stage: keep the latest attempt per chapter
    # (Stage A's game log is not prose and has no chapter id in its key).
    latest: dict[str, tuple[int, Path]] = {}
    for path_ in responses:
        chapter = CHAPTER_RE.search(path_.stem)
        if not chapter:
            continue
        attempt = ATTEMPT_RE.search(path_.stem)
        number = int(attempt.group(1)) if attempt else 1
        key = chapter.group(1)
        if key not in latest or number >= latest[key][0]:
            latest[key] = (number, path_)
    documents: list[Document] = []
    for chapter, (_attempt, path_) in sorted(latest.items()):
        payload = json.loads(path_.read_text(encoding="utf-8"))
        text = payload.get("text")
        if not isinstance(text, str) or not text.strip():
            raise SystemExit(f"{path_}: not a relay response (no 'text')")
        staged = scratch / f"{chapter}.md"
        staged.write_text(text, encoding="utf-8")
        documents.append(Document(path=staged, text=text))
    if not documents:
        raise SystemExit(f"arm has no chapter files or relay responses: {path}")
    return documents, "relay_responses"


def _relative(path: Path) -> str:
    """Keep recorded paths portable: no absolute workspace paths in the JSON."""
    try:
        return str(path.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def _sha256_tree(directory: Path) -> dict[str, str]:
    return {path.name: hashlib.sha256(path.read_bytes()).hexdigest()
            for path in sorted(directory.rglob("*")) if path.is_file()}


def profile(documents: list[Document], canon: Path, patterns: list[dict],
            task) -> dict:
    joined = "\n\n".join(document.text for document in documents)
    stripped = MARKER_RE.sub("", joined)
    markers = MARKER_RE.findall(joined)
    kinds: dict[str, int] = {}
    for marker in markers:
        kinds[marker[2:].split(":", 1)[0].strip()] = kinds.get(
            marker[2:].split(":", 1)[0].strip(), 0) + 1
    stats = measure(documents)
    forbidden = find_forbidden(documents, patterns)
    chars = len(re.sub(r"\s", "", stripped))
    hits = {term: term in joined for term in task.must_include}
    avoid_hits = {term: joined.count(term) for term in task.avoid}
    audit = audit_texts(canon, documents[0].path.parent)
    summary = audit["summary"]
    return {
        "documents": len(documents),
        "chars": chars,
        "chars_with_markers": len(re.sub(r"\s", "", joined)),
        "per_chapter_chars": {document.path.stem: len(
            re.sub(r"\s", "", MARKER_RE.sub("", document.text)))
            for document in documents},
        "markers": {"total": len(markers), "by_kind": kinds},
        "must_include": {"hits": hits,
                         "rate": round(sum(hits.values()) / len(hits), 3)
                         if hits else 1.0},
        "task_avoid_hits": avoid_hits,
        "forbidden": {"hits": len(forbidden),
                      "per_10k_chars": density(len(forbidden), chars),
                      "evidence": forbidden},
        "audit": {"violations": summary["violations"],
                  "by_severity": summary["by_severity"],
                  "by_type": summary.get("by_type", {}),
                  "checks_skipped": summary["checks_skipped"],
                  "ced_per_10k_chars": summary["ced_per_10k_chars"]},
        "style": {"dialogue_ratio": stats["dialogue_ratio"],
                  "paragraphs": stats["paragraphs"],
                  "mean_paragraph_chars": stats["mean_paragraph_chars"],
                  "sentence_length_cv": stats["style"]["sentence_length_cv"],
                  "sentence_count": stats["style"]["sentence_count"]},
    }


def _delta(base: dict, other: dict) -> dict:
    """Only arithmetic differences; no interpretation is attached."""
    def pick(profile_, *keys):
        value = profile_
        for key in keys:
            value = value[key]
        return value

    rows = {
        "chars": ("chars",),
        "dialogue_ratio": ("style", "dialogue_ratio"),
        "sentence_length_cv": ("style", "sentence_length_cv"),
        "mean_paragraph_chars": ("style", "mean_paragraph_chars"),
        "must_include_rate": ("must_include", "rate"),
        "forbidden_per_10k_chars": ("forbidden", "per_10k_chars"),
        "violations": ("audit", "violations"),
        "ced_per_10k_chars": ("audit", "ced_per_10k_chars"),
    }
    out = {}
    for label, keys in rows.items():
        left, right = pick(base, *keys), pick(other, *keys)
        out[label] = {"first": left, "second": right,
                      "difference": None if left is None or right is None
                      else round(right - left, 3)}
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--task", required=True)
    parser.add_argument("--canon", required=True,
                        help="canon directory used by both arms")
    parser.add_argument("--arm", action="append", required=True,
                        metavar="NAME=PATH", help="repeat for each arm")
    parser.add_argument("--tasks-file", default=str(DEFAULT_TASKS))
    parser.add_argument("--patterns", default=str(DEFAULT_PATTERNS))
    parser.add_argument("--out", help="write the comparison JSON here")
    parser.add_argument("--model", default="arena-agent-mode",
                        help="operator model recorded for both arms")
    parser.add_argument("--model-version", default="unversioned",
                        help="operator version; G5 stays unmet without one")
    parser.add_argument("--label", default="first/second",
                        help="how to name the two arms in the delta block")
    args = parser.parse_args(argv)

    tasks = load_tasks(args.tasks_file)
    task = tasks.get(args.task)
    patterns = load_patterns(args.patterns)
    canon = Path(args.canon)
    if not canon.is_dir():
        raise SystemExit(f"canon directory not found: {canon}")

    if len(args.arm) != 2:
        raise SystemExit("exactly two --arm entries are needed for a comparison")

    arms: dict[str, dict] = {}
    with tempfile.TemporaryDirectory() as scratch_root:
        for index, entry in enumerate(args.arm):
            name, _, path = entry.partition("=")
            if not name or not path:
                raise SystemExit(f"--arm needs NAME=PATH, got {entry!r}")
            scratch = Path(scratch_root) / f"arm-{index}"
            scratch.mkdir(parents=True, exist_ok=True)
            documents, source = load_arm(Path(path), scratch)
            arms[name] = {"source": source, "path": _relative(Path(path)),
                          "text_sha256": {
                              document.path.stem: hashlib.sha256(
                                  document.text.encode("utf-8")).hexdigest()
                              for document in documents},
                          **profile(documents, canon, patterns, task)}

    first, second = list(arms)
    report = {
        "schema": "l1-arm-comparison-v1",
        "scope": ("L1 only: structure and hygiene. Descriptive reference "
                  "values, not protocol-v1 pass, quality or preference."),
        "evaluation_scope": load_evaluation_scope(),
        "provider": {"model": args.model, "model_version": args.model_version,
                     "note": ("Both arms were written by the same operator, "
                              "which is not a versioned model. G5 is not "
                              "claimed and the numbers are reference values.")},
        "task": args.task,
        "canon": _relative(canon),
        "canon_sha256": _sha256_tree(canon),
        "patterns": {"path": _relative(Path(args.patterns)),
                     "count": len(patterns),
                     "sha256": hashlib.sha256(
                         Path(args.patterns).read_bytes()).hexdigest()},
        "arms": arms,
        "delta": {"schema": "second minus first",
                  "labels": {first: "first", second: "second"},
                  **{first: _delta(arms[first], arms[second])}},
        "limits": [
            "N=1 per arm, one task, one operator: the two arms are not "
            "independent samples and no interval is meaningful.",
            "The same agent wrote both arms and has read the checker code; "
            "the operator is not a fixed model version (G5 unmet).",
            "The arms are given different inputs (a verified game log vs the "
            "design documents alone), so a difference is a difference between "
            "conditions, not an effect of a controllable variable.",
            "Characters, dialogue ratio and sentence length are descriptive; "
            "do not read them as quality.",
        ],
    }
    text = json.dumps(report, ensure_ascii=False, indent=2) + "\n"
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
    print(json.dumps({name: {
        "chars": arm["chars"],
        "must_include": arm["must_include"]["rate"],
        "forbidden_per_10k": arm["forbidden"]["per_10k_chars"],
        "violations": arm["audit"]["violations"],
        "ced_per_10k": arm["audit"]["ced_per_10k_chars"],
        "dialogue_ratio": arm["style"]["dialogue_ratio"],
        "sentence_cv": arm["style"]["sentence_length_cv"],
        "markers": arm["markers"]["total"],
    } for name, arm in arms.items()}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
